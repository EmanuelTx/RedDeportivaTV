import { chromium } from "playwright-core";
const S = "https://reddeportivatv.pages.dev";
const REAL = "torneo-integracion-de-la-plaza-san-isidro-libre-sport-caaguazu-vs-san-luis";
const nav = await chromium.launch({ channel: "msedge", headless: true });
const ctx = await nav.newContext({ viewport: { width: 1366, height: 800 } });
let paso = "inicio"; const hallazgos = [];
const nueva = async () => { const p = await ctx.newPage(); p.on("console", (m) => { if (m.type() === "error" && /ViewTransition|Transition/.test(m.text())) hallazgos.push(paso + " @ " + p.url().replace(S, "")); }); return p; };
let p = await nueva();
const ir = async (etiqueta, fn) => { paso = etiqueta; await fn(); await p.waitForTimeout(400); };
await ir("goto /", () => p.goto(S + "/", { waitUntil: "networkidle" }));
await ir("goto /noticias (goto directo)", () => p.goto(S + "/noticias", { waitUntil: "networkidle" }));
await ir("click noticia", async () => { await p.locator("a[href='/noticias/area-4-semifinal']").first().click(); await p.waitForLoadState("networkidle"); });
await ir("goto 404", () => p.goto(S + "/noticias/no-existe-xyz"));
await ir("goto /coberturas", () => p.goto(S + "/coberturas", { waitUntil: "networkidle" }));
await ir("click tarjeta día", async () => { await p.locator(".tarjeta--dia a").first().click(); await p.waitForLoadState("networkidle"); });
await ir("click partido", async () => { await p.locator("a[href='/coberturas/" + REAL + "']").first().click(); await p.waitForLoadState("networkidle"); });
await ir("buscar (envío de formulario)", async () => { await p.goto(S + "/coberturas", { waitUntil: "networkidle" }); const b = p.locator("input[name='q']").first(); await b.fill("san luis"); await b.press("Enter"); await p.waitForLoadState("networkidle"); });
await ir("goto archivo", () => p.goto(S + "/coberturas/archivo", { waitUntil: "networkidle" }));
paso = "cerrar página"; await p.close(); await new Promise((r) => setTimeout(r, 800));
console.log(hallazgos.length ? hallazgos : "sin avisos");
await nav.close();
